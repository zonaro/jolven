"""Tests for the per-game UZDoom mod selection.

The module under test lives behind Gtk/GSettings imports (``cartridges.shared``
is generated by Meson and does not exist in a bare source tree), so the code
exercised here is taken apart instead of imported: the field of ``Game`` and
the serialization of ``FileManager`` are read from the AST, and the pure
helpers of the dialog are compiled on their own. Everything asserted here
runs with no display, no GTK and no GSettings database.
"""

import ast
import json
import logging
import os
import shutil
import tempfile
import types
import unittest
from pathlib import Path
from typing import Any, Optional
from unittest.mock import patch

from cartridges.importer import uzdoom_config


ROOT = Path(__file__).parents[1]


def _parse(relative: str) -> ast.Module:
    return ast.parse((ROOT / relative).read_text(encoding="utf-8"))


def _class_node(tree: ast.Module, name: str) -> ast.ClassDef:
    return next(
        node
        for node in tree.body
        if isinstance(node, ast.ClassDef) and node.name == name
    )


def _serialized_names(function: ast.FunctionDef) -> set[str]:
    for node in ast.walk(function):
        if isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == "attrs"
            for target in node.targets
        ):
            return {
                item.value
                for item in node.value.elts
                if isinstance(item, ast.Constant) and isinstance(item.value, str)
            }
    return set()


class _FakeGame:
    """Stand-in game whose missing fields serialize as ``None``."""

    def __init__(self, **values: Any) -> None:
        self.__dict__.update(values)

    def __getattr__(self, _name: str) -> None:
        return None


class GameFieldTests(unittest.TestCase):
    """The ``uzdoom_mods`` field of ``Game``."""

    def _game_class(self) -> ast.ClassDef:
        return _class_node(_parse("cartridges/game.py"), "Game")

    def _field(self) -> ast.AnnAssign:
        return next(
            node
            for node in self._game_class().body
            if isinstance(node, ast.AnnAssign)
            and isinstance(node.target, ast.Name)
            and node.target.id == "uzdoom_mods"
        )

    def test_field_exists_with_an_empty_default(self) -> None:
        field = self._field()
        self.assertIsInstance(field.value, ast.List)
        self.assertEqual(field.value.elts, [])

    def test_field_is_an_ordered_list_of_strings(self) -> None:
        field = self._field()
        self.assertEqual(ast.unparse(field.annotation), "list[str]")

    def test_instance_copies_the_list(self) -> None:
        """The shared default must not leak between two games."""

        init = next(
            node
            for node in self._game_class().body
            if isinstance(node, ast.FunctionDef) and node.name == "__init__"
        )
        copies = [
            node
            for node in ast.walk(init)
            if isinstance(node, ast.Assign)
            and any(
                isinstance(target, ast.Attribute)
                and target.attr == "uzdoom_mods"
                for target in node.targets
            )
        ]
        self.assertTrue(copies)
        self.assertIn(
            "list(self.uzdoom_mods or [])",
            ast.unparse(copies[0]),
        )

    def test_old_json_without_field_defaults_to_an_empty_list(self) -> None:
        game_class = self._game_class()
        field = self._field()
        update_values = next(
            node
            for node in game_class.body
            if isinstance(node, ast.FunctionDef) and node.name == "update_values"
        )
        synthetic = ast.ClassDef(
            name="TestGame",
            bases=[],
            keywords=[],
            body=[field, update_values],
            decorator_list=[],
        )
        module = ast.fix_missing_locations(ast.Module(body=[synthetic], type_ignores=[]))
        namespace: dict[str, Any] = {"Any": Any}
        exec(compile(module, "game.py", "exec"), namespace)  # pylint: disable=exec-used
        game = namespace["TestGame"]()
        game.update_values({"name": "Legacy Game"})
        self.assertEqual(game.uzdoom_mods, [])

    def test_present_field_is_applied(self) -> None:
        game_class = self._game_class()
        field = self._field()
        update_values = next(
            node
            for node in game_class.body
            if isinstance(node, ast.FunctionDef) and node.name == "update_values"
        )
        synthetic = ast.ClassDef(
            name="TestGame",
            bases=[],
            keywords=[],
            body=[field, update_values],
            decorator_list=[],
        )
        module = ast.fix_missing_locations(ast.Module(body=[synthetic], type_ignores=[]))
        namespace: dict[str, Any] = {"Any": Any}
        exec(compile(module, "game.py", "exec"), namespace)  # pylint: disable=exec-used
        game = namespace["TestGame"]()
        game.update_values({"uzdoom_mods": ["/mods/one.wad", "/mods/two.pk3"]})
        self.assertEqual(game.uzdoom_mods, ["/mods/one.wad", "/mods/two.pk3"])


class LaunchIntegrationTests(unittest.TestCase):
    """The mods reach the command line of a UZDoom game."""

    def test_game_imports_the_command_builder(self) -> None:
        tree = _parse("cartridges/game.py")
        imported = False
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom) and node.module == "cartridges.game_launch":
                imported = any(
                    alias.name == "append_uzdoom_mods" for alias in node.names
                )
        self.assertTrue(imported)

    def test_launch_appends_the_mods(self) -> None:
        tree = _parse("cartridges/game.py")
        launch = next(
            node
            for node in _class_node(tree, "Game").body
            if isinstance(node, ast.FunctionDef) and node.name == "launch"
        )
        calls = [
            node
            for node in ast.walk(launch)
            if isinstance(node, ast.Call)
            and isinstance(node.func, ast.Name)
            and node.func.id == "append_uzdoom_mods"
        ]
        self.assertEqual(len(calls), 1)

    def test_mods_are_only_appended_for_uzdoom_games(self) -> None:
        tree = _parse("cartridges/game.py")
        launch = next(
            node
            for node in _class_node(tree, "Game").body
            if isinstance(node, ast.FunctionDef) and node.name == "launch"
        )
        compares = [
            node
            for node in ast.walk(launch)
            if isinstance(node, ast.Compare)
            and isinstance(node.left, ast.Attribute)
            and node.left.attr == "base_source"
        ]
        self.assertTrue(
            any(
                isinstance(operand, ast.Constant) and operand.value == "uzdoom"
                for compare in compares
                for operand in compare.comparators
            )
        )


class FileManagerSerializationTests(unittest.TestCase):
    def setUp(self) -> None:
        tree = _parse("cartridges/store/managers/file_manager.py")
        self.main = next(
            node
            for node in _class_node(tree, "FileManager").body
            if isinstance(node, ast.FunctionDef) and node.name == "main"
        )

    def test_uzdoom_mods_is_serialized(self) -> None:
        self.assertIn("uzdoom_mods", _serialized_names(self.main))

    def test_round_trip_preserves_the_order(self) -> None:
        mods = ["/mods/first.wad", "/mods/second.pk3", "/mods/third.wad"]
        with tempfile.TemporaryDirectory() as directory:
            games_dir = Path(directory)
            namespace: dict[str, Any] = {
                "json": json,
                "shared": types.SimpleNamespace(games_dir=games_dir),
                "Game": object,
            }
            module = ast.fix_missing_locations(
                ast.Module(body=[self.main], type_ignores=[])
            )
            exec(compile(module, "file_manager.py", "exec"), namespace)  # pylint: disable=exec-used
            namespace["main"](
                None,
                _FakeGame(uzdoom_mods=mods, game_id="rt-1"),
                {"skip_save": False},
            )

            saved = json.loads((games_dir / "rt-1.json").read_text(encoding="utf-8"))
            self.assertEqual(saved["uzdoom_mods"], mods)


class _StubSchema:
    """The part of GSettings the dialog reads."""

    def __init__(self) -> None:
        self.strings: dict[str, str] = {}

    def get_string(self, key: str) -> str:
        return self.strings.get(key, "")


class _StubShared:
    def __init__(self) -> None:
        self.schema = _StubSchema()


def _load_helpers() -> dict[str, Any]:
    """Compile the pure helpers of the dialog without importing GTK."""

    tree = _parse("cartridges/uzdoom_mods_dialog.py")
    wanted_constants = {"PWAD_MAGIC", "ARCHIVE_SUFFIXES"}
    wanted_functions = {
        "scan_mods",
        "merge_mods",
        "schema_folder",
        "detected_folder",
    }
    body = [
        node
        for node in tree.body
        if (
            isinstance(node, ast.Assign)
            and any(
                isinstance(target, ast.Name) and target.id in wanted_constants
                for target in node.targets
            )
        )
        or (
            isinstance(node, ast.FunctionDef) and node.name in wanted_functions
        )
    ]

    # The methods of the dialog that resolve the folders are compiled as
    # plain functions: they do not touch the widgets.
    dialog = _class_node(tree, "UzdoomModsDialog")
    for method in ("mod_folder", "wads_folder"):
        node = next(
            item
            for item in dialog.body
            if isinstance(item, ast.FunctionDef) and item.name == method
        )
        node.decorator_list = []
        body.append(node)

    module = ast.fix_missing_locations(ast.Module(body=body, type_ignores=[]))
    namespace: dict[str, Any] = {
        "Path": Path,
        "Optional": Optional,
        "logging": logging,
        "os": os,
        "shared": _StubShared(),
        "uzdoom_config": uzdoom_config,
    }
    exec(compile(module, "uzdoom_mods_dialog.py", "exec"), namespace)  # pylint: disable=exec-used
    return namespace


class ScanModsTests(unittest.TestCase):
    def setUp(self) -> None:
        self.namespace = _load_helpers()
        self.scan_mods = self.namespace["scan_mods"]
        self.merge_mods = self.namespace["merge_mods"]
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.folder = Path(self._tmp.name)

    def _write(self, name: str, content: bytes) -> Path:
        path = self.folder / name
        path.write_bytes(content)
        return path

    def test_pwad_is_a_mod(self) -> None:
        path = self._write("cool.wad", b"PWAD" + b"\x00" * 16)
        self.assertEqual(self.scan_mods(self.folder), [str(path)])

    def test_iwad_is_not_a_mod(self) -> None:
        self._write("doom2.wad", b"IWAD" + b"\x00" * 16)
        self.assertEqual(self.scan_mods(self.folder), [])

    def test_other_files_are_ignored(self) -> None:
        self._write("readme.txt", b"PWAD")
        self._write("notes.wad", b"nope")
        self.assertEqual(self.scan_mods(self.folder), [])

    def test_archives_are_mods_without_reading_them(self) -> None:
        self._write("pack.pk3", b"PK\x03\x04")
        self._write("pack.ipk3", b"PK\x03\x04")
        self.assertEqual(
            [Path(path).name for path in self.scan_mods(self.folder)],
            ["pack.ipk3", "pack.pk3"],
        )

    def test_missing_folder_has_no_mods(self) -> None:
        self.assertEqual(self.scan_mods(self.folder / "nope"), [])

    def test_no_folder_has_no_mods(self) -> None:
        self.assertEqual(self.scan_mods(None), [])

    def test_mods_are_sorted_by_name(self) -> None:
        self._write("b.wad", b"PWAD")
        self._write("a.wad", b"PWAD")
        self.assertEqual(
            [Path(path).name for path in self.scan_mods(self.folder)],
            ["a.wad", "b.wad"],
        )


class MergeModsTests(unittest.TestCase):
    def setUp(self) -> None:
        self.namespace = _load_helpers()
        self.merge_mods = self.namespace["merge_mods"]

    def test_saved_mods_come_first_in_their_order(self) -> None:
        merged = self.merge_mods(
            ["/mods/c.wad", "/mods/a.wad", "/mods/b.wad"],
            ["/mods/b.wad", "/mods/a.wad"],
        )
        self.assertEqual(merged, ["/mods/b.wad", "/mods/a.wad", "/mods/c.wad"])

    def test_saved_mod_that_is_gone_is_kept(self) -> None:
        merged = self.merge_mods(["/mods/a.wad"], ["/mods/a.wad", "/mods/gone.wad"])
        self.assertEqual(merged, ["/mods/a.wad", "/mods/gone.wad"])

    def test_nothing_saved_keeps_the_found_order(self) -> None:
        merged = self.merge_mods(["/mods/b.wad", "/mods/a.wad"], [])
        self.assertEqual(merged, ["/mods/b.wad", "/mods/a.wad"])


class UnionScanTests(unittest.TestCase):
    """The mods of the mods folder and of the WADs folder are listed."""

    def setUp(self) -> None:
        self.namespace = _load_helpers()
        self.scan_mods = self.namespace["scan_mods"]
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.root = Path(self._tmp.name)
        self.mods = self.root / "mods"
        self.wads = self.root / "wads"
        self.mods.mkdir()
        self.wads.mkdir()

    def _write(self, folder: Path, name: str, content: bytes) -> Path:
        path = folder / name
        path.write_bytes(content)
        return path

    def test_a_mod_of_the_wads_folder_is_found(self) -> None:
        mod = self._write(self.wads, "cool.wad", b"PWAD" + b"\x00" * 16)
        self.assertEqual(self.scan_mods([self.mods, self.wads]), [str(mod)])

    def test_the_same_folder_is_scanned_once(self) -> None:
        mod = self._write(self.mods, "cool.wad", b"PWAD" + b"\x00" * 16)
        self.assertEqual(self.scan_mods([self.mods, self.mods]), [str(mod)])

    def test_the_mods_of_both_folders_are_listed(self) -> None:
        first = self._write(self.mods, "a.wad", b"PWAD")
        second = self._write(self.wads, "b.wad", b"PWAD")
        self.assertEqual(
            self.scan_mods([self.mods, self.wads]), [str(first), str(second)]
        )

    def test_a_single_folder_is_still_accepted(self) -> None:
        mod = self._write(self.mods, "cool.wad", b"PWAD")
        self.assertEqual(self.scan_mods(self.mods), [str(mod)])


class ModFolderTests(unittest.TestCase):
    """The chain of the folders that hold the mods."""

    def setUp(self) -> None:
        self.namespace = _load_helpers()
        self.shared = self.namespace["shared"]
        self.mod_folder = self.namespace["mod_folder"]
        self.wads_folder = self.namespace["wads_folder"]
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.root = Path(self._tmp.name)
        self.mods = self.root / "mods"
        self.wads = self.root / "wads"
        self.mods.mkdir()
        self.wads.mkdir()
        # The configuration of the machine that runs the tests is never
        # read: the detection is replaced by an empty list.
        patcher = patch.object(uzdoom_config, "search_dirs", lambda *a, **k: [])
        patcher.start()
        self.addCleanup(patcher.stop)

    def _set(self, key: str, value: str) -> None:
        self.shared.schema.strings[key] = value

    def test_the_folder_of_the_preferences_wins(self) -> None:
        self._set("uzdoom-mods-location", str(self.mods))
        self._set("uzdoom-location", str(self.wads))
        self.assertEqual(self.mod_folder(), self.mods)

    def test_the_detected_folder_is_used_next(self) -> None:
        with patch.object(
            uzdoom_config, "search_dirs", lambda section, **k: [str(self.mods)]
        ):
            self.assertEqual(self.mod_folder(), self.mods)

    def test_the_wads_folder_is_the_last_resort(self) -> None:
        self._set("uzdoom-location", str(self.wads))
        self.assertEqual(self.mod_folder(), self.wads)

    def test_nothing_is_known(self) -> None:
        self.assertIsNone(self.mod_folder())

    def test_a_folder_that_is_gone_is_not_used(self) -> None:
        self._set("uzdoom-mods-location", str(self.root / "gone"))
        self._set("uzdoom-location", str(self.wads))
        self.assertEqual(self.mod_folder(), self.wads)

    def test_the_wads_folder_falls_back_to_the_detection(self) -> None:
        with patch.object(
            uzdoom_config, "search_dirs", lambda section, **k: [str(self.wads)]
        ):
            self.assertEqual(self.wads_folder(), self.wads)

    def test_the_wads_folder_of_the_preferences_wins(self) -> None:
        self._set("uzdoom-location", str(self.wads))
        self.assertEqual(self.wads_folder(), self.wads)


